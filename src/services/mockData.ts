export function calculateDeltaAndPercent(
  current: number,
  previous: number | null
): { delta: number | null; percentChange: number | null } {
  if (previous === null || previous === undefined) {
    return { delta: null, percentChange: null };
  }
  const delta = Number((current - previous).toFixed(2));
  if (previous === 0) {
    return { delta, percentChange: current === 0 ? 0 : 100 };
  }
  const percentChange = Number((((current - previous) / Math.abs(previous)) * 100).toFixed(1));
  return { delta, percentChange };
}

